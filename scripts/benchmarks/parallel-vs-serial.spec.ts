import { describe, it, expect } from 'vitest';
import { writeFile, readFile, mkdir } from 'node:fs/promises';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

/**
 * SC-18 benchmark — measures wallclock improvement of parallel dispatch
 * over forced-serial dispatch on a synthetic multi-task fixture.
 *
 * Fixture: 4 disjoint tasks each simulating a 200ms tool call (Promise + setTimeout).
 * Serial baseline: await each in sequence.
 * Parallel run:    Promise.all of all 4.
 *
 * Assertion: parallel_wallclock <= serial_wallclock * 0.80
 *            (i.e., >=20% improvement; SC-18 threshold).
 *
 * Determinism: each task uses fixed-timing setTimeout; Node event-loop
 * jitter is absorbed by the 20% margin and a 3-run median.
 */

interface FixtureTask {
  id: string;
  durationMs: number;
}

const FIXTURE: FixtureTask[] = [
  { id: 't1', durationMs: 200 },
  { id: 't2', durationMs: 200 },
  { id: 't3', durationMs: 200 },
  { id: 't4', durationMs: 200 },
];

async function runTask(task: FixtureTask): Promise<{ id: string; finishedAt: number }> {
  await new Promise(r => setTimeout(r, task.durationMs));
  return { id: task.id, finishedAt: Date.now() };
}

async function runSerial(tasks: FixtureTask[]): Promise<number> {
  const start = Date.now();
  for (const t of tasks) { await runTask(t); }
  return Date.now() - start;
}

async function runParallel(tasks: FixtureTask[]): Promise<number> {
  const start = Date.now();
  await Promise.all(tasks.map(runTask));
  return Date.now() - start;
}

function median(xs: number[]): number {
  const sorted = [...xs].sort((a, b) => a - b);
  return sorted[Math.floor(sorted.length / 2)]!;
}

interface BenchmarkResult {
  serialMedianMs: number;
  parallelMedianMs: number;
  improvementRatio: number;
  runs: number;
  fixtureTaskCount: number;
  fixturePerTaskMs: number;
}

async function recordBenchmarkResult(result: BenchmarkResult): Promise<void> {
  // Resolve path relative to repo root (two dirs up from scripts/benchmarks/)
  const __filename = fileURLToPath(import.meta.url);
  const __dirname = dirname(__filename);
  const repoRoot = join(__dirname, '..', '..');
  const outputPath = join(repoRoot, 'agent-workspace', 'memory', 'parallel-benchmark-result.md');

  await mkdir(dirname(outputPath), { recursive: true });

  const timestamp = new Date().toISOString();
  const improvementPct = (result.improvementRatio * 100).toFixed(1);
  const ratioFormatted = (result.parallelMedianMs / result.serialMedianMs).toFixed(3);

  // Check if file already exists to decide between create vs append
  let existing = '';
  try {
    existing = await readFile(outputPath, 'utf8');
  } catch {
    // File doesn't exist yet — first run, create fresh
  }

  const row = `| ${timestamp} | ${result.runs} | ${result.fixtureTaskCount} | ${result.fixturePerTaskMs} | ${result.serialMedianMs} | ${result.parallelMedianMs} | ${ratioFormatted} | ${improvementPct}% | ${result.improvementRatio >= 0.20 ? 'PASS' : 'FAIL'} |`;

  if (!existing) {
    const header = `# SC-18 — Parallel-vs-Serial Benchmark Results

> Auto-generated by \`scripts/benchmarks/parallel-vs-serial.spec.ts\`.
> Each row is one vitest run. The assertion threshold is **parallel <= 80% of serial** (>=20% improvement).

| Timestamp | Runs | Tasks | Per-task ms | Serial median ms | Parallel median ms | Parallel/Serial ratio | Improvement | SC-18 |
|-----------|------|-------|-------------|------------------|--------------------|-----------------------|-------------|-------|
${row}
`;
    await writeFile(outputPath, header, 'utf8');
  } else {
    // Append a new row — find the last line and append
    const trimmed = existing.trimEnd();
    await writeFile(outputPath, `${trimmed}\n${row}\n`, 'utf8');
  }
}

describe('SC-18 — parallel-vs-serial wallclock benchmark', () => {
  it('parallel <= 80% of serial wallclock (>=20% improvement)', async () => {
    const RUNS = 3;
    const serialRuns: number[] = [];
    const parallelRuns: number[] = [];
    for (let i = 0; i < RUNS; i++) {
      serialRuns.push(await runSerial(FIXTURE));
      parallelRuns.push(await runParallel(FIXTURE));
    }
    const serialMedian = median(serialRuns);
    const parallelMedian = median(parallelRuns);

    // Record to memory file for phase-5-complete.md citation
    await recordBenchmarkResult({
      serialMedianMs: serialMedian,
      parallelMedianMs: parallelMedian,
      improvementRatio: 1 - parallelMedian / serialMedian,
      runs: RUNS,
      fixtureTaskCount: FIXTURE.length,
      fixturePerTaskMs: FIXTURE[0]!.durationMs,
    });

    expect(parallelMedian).toBeLessThanOrEqual(serialMedian * 0.80);
  }, 30_000); // 30s timeout: 3 runs × (800ms serial + ~200ms parallel) = ~3s; generous headroom for CI
});
